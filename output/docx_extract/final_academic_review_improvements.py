def clear_runs(paragraph):
    for run in list(paragraph.runs):
        run._element.getparent().remove(run._element)


def set_run_font(run, size=12, bold=False, italic=False):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    run.font.color.rgb = RGBColor(0, 0, 0)


def format_paragraph(paragraph, *, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_line=True,
                     line_spacing=1.5, before=0, after=6):
    paragraph.alignment = align
    paragraph.paragraph_format.first_line_indent = Cm(1.25) if first_line else Cm(0)
    paragraph.paragraph_format.line_spacing = line_spacing
    paragraph.paragraph_format.space_before = Pt(before)
    paragraph.paragraph_format.space_after = Pt(after)


def set_text(paragraph, text, *, size=12, bold=False, italic=False,
             align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_line=True):
    clear_runs(paragraph)
    run = paragraph.add_run(text)
    set_run_font(run, size=size, bold=bold, italic=italic)
    format_paragraph(paragraph, align=align, first_line=first_line)


def set_mixed_label(paragraph, label, body):
    clear_runs(paragraph)
    r1 = paragraph.add_run(label)
    set_run_font(r1, bold=True)
    r2 = paragraph.add_run(body)
    set_run_font(r2)
    format_paragraph(paragraph, align=WD_ALIGN_PARAGRAPH.LEFT, first_line=False)


def insert_paragraph_after(paragraph, text=None):
    new_p = OxmlElement("w:p")
    paragraph._p.addnext(new_p)
    new_para = Paragraph(new_p, paragraph._parent)
    if text:
        set_text(new_para, text)
    return new_para


def replace_exact(paragraphs, old, new):
    for p in paragraphs:
        if " ".join(p.text.split()) == old:
            set_text(p, new)
            return True
    return False


def replace_contains(paragraphs, needle, new):
    for p in paragraphs:
        if needle in " ".join(p.text.split()):
            set_text(p, new)
            return True
    return False


def style_cell(cell, header=False):
    for p in cell.paragraphs:
        format_paragraph(
            p,
            align=WD_ALIGN_PARAGRAPH.CENTER if header else WD_ALIGN_PARAGRAPH.LEFT,
            first_line=False,
            line_spacing=1.0,
            after=2,
        )
        for run in p.runs:
            set_run_font(run, size=9, bold=header)


def set_cell(cell, text, header=False):
    p = cell.paragraphs[0]
    clear_runs(p)
    r = p.add_run(text)
    set_run_font(r, size=9, bold=header)
    format_paragraph(
        p,
        align=WD_ALIGN_PARAGRAPH.CENTER if header else WD_ALIGN_PARAGRAPH.LEFT,
        first_line=False,
        line_spacing=1.0,
        after=2,
    )


