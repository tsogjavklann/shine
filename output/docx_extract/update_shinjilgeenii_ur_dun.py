HEADING_1 = {151}
HEADING_2 = {153, 161, 167, 176, 182, 194}


def set_paragraph_text(paragraph, text: str) -> None:
    paragraph.text = text
    paragraph.alignment = None


def set_paragraph_image(paragraph, image_key: str) -> None:
    image_path = FIGURES[image_key]
    if not image_path.exists():
        raise FileNotFoundError(image_path)
    paragraph.clear()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.add_run().add_picture(str(image_path), width=Inches(5.8))


def set_table_content(table, data: list[list[str]]) -> None:
    while len(table.rows) < len(data):
        table.add_row()
    while len(table.rows) > len(data):
        row = table.rows[-1]
        row._tr.getparent().remove(row._tr)
    for row_idx, row_data in enumerate(data):
        row = table.rows[row_idx]
        for col_idx, cell in enumerate(row.cells):
            cell.text = row_data[col_idx] if col_idx < len(row_data) else ""


def move_table_after(table, paragraph) -> None:
    tbl = table._tbl
    tbl.getparent().remove(tbl)
    paragraph._p.addnext(tbl)


def main() -> None:
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup = BACKUP_DIR / f"bagiin_ner_v29_before_shinjilgeenii_ur_dun_{stamp}.docx"
    shutil.copy2(DOCX_PATH, backup)

    doc = Document(DOCX_PATH)

    for idx, item in PARAGRAPHS.items():
        kind, value = item
        paragraph = doc.paragraphs[idx]
        if idx in HEADING_1:
            paragraph.style = "Heading 1"
        elif idx in HEADING_2:
            paragraph.style = "Heading 2"
        else:
            paragraph.style = "Normal"
        if kind == "image":
            set_paragraph_image(paragraph, value)
        else:
            set_paragraph_text(paragraph, value)

    for table_idx, data in TABLES.items():
        set_table_content(doc.tables[table_idx], data)

    table_targets = {
        4: 155,
        5: 163,
        6: 173,
        7: 191,
        8: 195,
        9: 199,
    }
    table_objects = {idx: doc.tables[idx] for idx in table_targets}
    for table_idx, paragraph_idx in table_targets.items():
        move_table_after(table_objects[table_idx], doc.paragraphs[paragraph_idx])

    saved_path = DOCX_PATH
    try:
        doc.save(DOCX_PATH)
    except PermissionError:
        FALLBACK_PATH.parent.mkdir(parents=True, exist_ok=True)
        doc.save(FALLBACK_PATH)
        saved_path = FALLBACK_PATH

    with zipfile.ZipFile(saved_path) as zf:
        bad = zf.testzip()
        if bad:
            raise RuntimeError(f"Invalid docx zip member: {bad}")

    print(f"Updated results section in {saved_path}")
    print(f"Backup: {backup}")
    print(f"Figures inserted: {len(FIGURES)}")
    if saved_path != DOCX_PATH:
        print("Original was locked; fallback copy was written.")


if __name__ == "__main__":
    main()
