def main() -> None:
    docx_path = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("bagiin_ner_v29.docx")
    backup_dir = Path("output/docx_backups")
    backup_dir.mkdir(parents=True, exist_ok=True)
    backup_path = backup_dir / f"{docx_path.stem}_before_orshil_{datetime.now():%Y%m%d_%H%M%S}.docx"
    shutil.copy2(docx_path, backup_path)

    doc = Document(docx_path)
    start = end = None
    for idx, para in enumerate(doc.paragraphs):
        text = para.text.strip()
        if text == "ОРШИЛ":
            start = idx
        elif start is not None and text.startswith("I БҮЛЭГ."):
            end = idx
            break

    if start is None or end is None:
        raise RuntimeError("Could not safely locate the ОРШИЛ block.")

    slots = list(range(start + 1, end))
    nonempty_slots = [idx for idx in slots if doc.paragraphs[idx].text.strip()]
    if len(nonempty_slots) != len(NEW_INTRO):
        raise RuntimeError(
            f"Expected {len(NEW_INTRO)} intro body paragraphs, found {len(nonempty_slots)}."
        )

    for idx, text in zip(nonempty_slots, NEW_INTRO):
        doc.paragraphs[idx].text = text

    doc.save(docx_path)
    print(f"Updated: {docx_path}")
    print(f"Backup: {backup_path}")


if __name__ == "__main__":
    main()
